// Run the actual entrypoint in a subprocess, including signal handling.
func TestDaemonHelper(t *testing.T) {
	if os.Getenv("DFMPD_TEST_HELPER") != "1" {
		return
	}
	os.Args = []string{os.Args[0], "-mpv", os.Getenv("DFMPD_TEST_MPV")}
	main()
	os.Exit(0)
}
func TestDaemonLifecycle(t *testing.T) {
	if _, err := exec.LookPath("mpv"); err != nil {
		t.Skip("mpv not installed")
	}
	for _, signal := range []syscall.Signal{syscall.SIGTERM, syscall.SIGINT} {
		t.Run(signal.String(), func(t *testing.T) { testDaemon(t, signal) })
	}
}
func testDaemon(t *testing.T, signal syscall.Signal) {
	dir, err := os.MkdirTemp("", "dfmpd-process-")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(dir)
	pidPath := filepath.Join(dir, "mpv.pid")
	wrapper := filepath.Join(dir, "mpv-null")
	// Temp paths are generated by this test, not user input.
	script := "#!/bin/sh\nprintf '%s' \"$$\" > '" + pidPath + "'\nexec mpv --ao=null \"$@\"\n"
	if err := os.WriteFile(wrapper, []byte(script), 0700); err != nil {
		t.Fatal(err)
	}
	file := filepath.Join(dir, "audio.wav")
	data := make([]byte, 44+320000)
	copy(data, "RIFF")
	binary.LittleEndian.PutUint32(data[4:], uint32(len(data)-8))
	copy(data[8:], "WAVEfmt ")
	binary.LittleEndian.PutUint32(data[16:], 16)
	binary.LittleEndian.PutUint16(data[20:], 1)
	binary.LittleEndian.PutUint16(data[22:], 1)
	binary.LittleEndian.PutUint32(data[24:], 8000)
	binary.LittleEndian.PutUint32(data[28:], 16000)
	binary.LittleEndian.PutUint16(data[32:], 2)
	binary.LittleEndian.PutUint16(data[34:], 16)
	copy(data[36:], "data")
	binary.LittleEndian.PutUint32(data[40:], 320000)
	if err := os.WriteFile(file, data, 0600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(os.Args[0], "-test.run=^TestDaemonHelper$")
	cmd.Env = append(os.Environ(), "DFMPD_TEST_HELPER=1", "DFMPD_TEST_MPV="+wrapper, "XDG_RUNTIME_DIR="+dir)
	var logs bytes.Buffer
	cmd.Stdout = &logs
	cmd.Stderr = &logs
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	done := make(chan struct{})
	var exitErr error
	go func() { exitErr = cmd.Wait(); close(done) }()
	defer func() { cmd.Process.Kill(); <-done }()
	socket := filepath.Join(dir, "dfmpd", "control.sock")
	var conn net.Conn
	deadline := time.Now().Add(7 * time.Second)
	for time.Now().Before(deadline) {
		conn, err = net.Dial("unix", socket)
		if err == nil {
			break
		}
		select {
		case <-done:
			t.Fatalf("daemon exited: %v %s", exitErr, logs.String())
		default:
		}
		time.Sleep(20 * time.Millisecond)
	}
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close()
	conn.SetDeadline(time.Now().Add(15 * time.Second))
	reader := bufio.NewReader(conn)
	call := func(method string, params any) map[string]json.RawMessage {
		t.Helper()
		if err := json.NewEncoder(conn).Encode(map[string]any{"jsonrpc": "2.0", "id": 1, "method": method, "params": params}); err != nil {
			t.Fatal(err)
		}
		line, err := reader.ReadBytes('\n')
		if err != nil {
			t.Fatal(err)
		}
		var out map[string]json.RawMessage
		if err := json.Unmarshal(line, &out); err != nil {
			t.Fatal(err)
		}
		return out
	}
	ok := func(method string, params any) {
		t.Helper()
		out := call(method, params)
		if out["error"] != nil {
			t.Fatalf("%s: %s", method, out["error"])
		}
	}
	empty := struct{}{}
	ok("daemon.info", empty)
	ok("playback.play", map[string]any{"location": file})
	waitState := func(want string) {
		t.Helper()
		deadline := time.Now().Add(3 * time.Second)
		for time.Now().Before(deadline) {
			out := call("playback.status", empty)
			var s struct {
				State string `json:"state"`
			}
			json.Unmarshal(out["result"], &s)
			if s.State == want {
				return
			}
			time.Sleep(20 * time.Millisecond)
		}
		t.Fatalf("state did not reach %s", want)
	}
	waitState("playing")
	ok("playback.pause", empty)
	waitState("paused")
	ok("playback.seek", map[string]any{"seconds": 2})
	ok("playback.resume", empty)
	waitState("playing")
	ok("playback.stop", empty)
	waitState("idle")
	// Disconnecting the controlling client must not terminate the session.
	ok("playback.play", map[string]any{"location": file})
	waitState("playing")
	conn.Close()
	conn, err = net.Dial("unix", socket)
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close()
	conn.SetDeadline(time.Now().Add(10 * time.Second))
	reader = bufio.NewReader(conn)
	waitState("playing")
	pidBytes, err := os.ReadFile(pidPath)
	if err != nil {
		t.Fatal(err)
	}
	pid, err := strconv.Atoi(strings.TrimSpace(string(pidBytes)))
	if err != nil {
		t.Fatal(err)
	}
	if signal == syscall.SIGINT {
		if err := syscall.Kill(pid, syscall.SIGKILL); err != nil {
			t.Fatal(err)
		}
		deadline := time.Now().Add(3 * time.Second)
		failed := false
		for time.Now().Before(deadline) {
			out := call("playback.status", empty)
			if out["error"] != nil {
				failed = true
				break
			}
			time.Sleep(20 * time.Millisecond)
		}
		if !failed {
			t.Fatal("mpv death not surfaced")
		}
		ok("daemon.info", empty)
	}
	if err := cmd.Process.Signal(signal); err != nil {
		t.Fatal(err)
	}
	select {
	case <-done:
		if exitErr != nil {
			t.Fatalf("shutdown: %v %s", exitErr, logs.String())
		}
	case <-time.After(6 * time.Second):
		t.Fatal("daemon did not exit")
	}
	if _, err := os.Stat(socket); !os.IsNotExist(err) {
		t.Fatalf("socket remains: %v", err)
	}
	if err := syscall.Kill(pid, 0); err != syscall.ESRCH {
		t.Fatalf("mpv remains or not reaped: %v", err)
	}
	matches, _ := filepath.Glob(filepath.Join(dir, "dfmpd-*"))
	if len(matches) != 0 {
		t.Fatalf("mpv socket directories remain: %v", matches)
	}
}
func TestStartupFailureCleanup(t *testing.T) {
	dir, err := os.MkdirTemp("", "dfmpd-start-")
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(dir)
	t.Setenv("XDG_RUNTIME_DIR", dir)
	if err := run(t.Context(), filepath.Join(dir, "missing-mpv")); err == nil {
		t.Fatal("startup should fail")
	}
	if _, err := os.Stat(filepath.Join(dir, "dfmpd", "control.sock")); !os.IsNotExist(err) {
		t.Fatalf("socket remains: %v", err)
	}
	entries, _ := os.ReadDir(dir)
	for _, entry := range entries {
		if entry.Name() != "dfmpd" {
			t.Fatal(fmt.Sprintf("unexpected leftover: %s", entry.Name()))
		}
	}
}
